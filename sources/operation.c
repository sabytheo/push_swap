#include "push_swap.h"

void	swap_a(t_node **stack_a)
{
	t_node	*first;
	t_node	*second;

	if (!stack_a || !(*stack_a)->next)
		return ;
	first = *stack_a;
	second = first->next;
	first->next = second->next;
	second->next = first;
	*stack_a = second;
	ft_printf("sa\n");
}

void	swap_b(t_node **stack_b)
{
	t_node	*first;
	t_node	*second;

	if (!stack_b || !(*stack_b)->next)
		return ;
	first = *stack_b;
	second = first->next;
	first->next = second->next;
	second->next = first;
	*stack_b = second;
	ft_printf("sb\n");
}

void	push_b(t_node **stack_a, t_node **stack_b)
{
	t_node	*temp;

	if (!stack_a)
		return ;
	temp = *stack_a;
	*stack_a = (*stack_a)->next;
	temp->next = *stack_b;
	*stack_b = temp;
	ft_printf("pb\n");
}

void	push_a(t_node **stack_b, t_node **stack_a)
{
	t_node	*temp;

	if (!stack_b)
		return ;
	temp = *stack_b;
	*stack_b = (*stack_b)->next;
	temp->next = *stack_a;
	*stack_a = temp;
	ft_printf("pa\n");
}
